// PreToolUse hook (matcher: Edit|Write|MultiEdit|NotebookEdit).
// Blocks edits to files CLAUDE.md says must never be hand-edited, and to secret files.
// Scripts that regenerate these files run through Bash, so they are not affected.
// Exit 2 = block and send stderr to Claude. Exit 0 = allow.

import path from 'node:path';

const PROTECTED = [
  [/^recordings-src\/live\//, 'recorded live runs are kept as they came out (CLAUDE.md honesty rules)'],
  [/^recordings-src\/archive-[^/]+\//, 'archived recordings are never edited'],
  [/^lib\/liveRecordings\.json$/, 'generated by `npm run recordings:live`'],
  [/^lib\/liveRecordings\//, 'generated by `npm run recordings:live`'],
  [/^lib\/exampleRequests\.ts$/, 'generated by `npm run recordings:live`'],
  [/^lib\/eval\/results\.json$/, 'append-only, real runs only, written by scripts/run-eval.ts'],
  [/(^|\/)\.env(?!\.example$)[^/]*$/, 'secret or local environment file'],
  [/^\.vercel\//, 'Vercel project link, never edited or committed'],
];

let raw = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => (raw += chunk));
process.stdin.on('end', () => {
  let input;
  try {
    input = JSON.parse(raw);
  } catch {
    // Unreadable input: allow, so a bad payload cannot lock Claude out of editing.
    process.exit(0);
  }

  const target = input?.tool_input?.file_path ?? input?.tool_input?.notebook_path ?? '';
  if (!target) process.exit(0);

  const root = process.env.CLAUDE_PROJECT_DIR || input?.cwd || process.cwd();
  const rel = path.relative(root, path.resolve(root, target)).split(path.sep).join('/');

  for (const [pattern, reason] of PROTECTED) {
    if (pattern.test(rel)) {
      console.error(
        `BLOCKED: '${rel}' is protected (${reason}). The user has prevented you from editing it. Ask them to change it or to run the script that regenerates it.`,
      );
      process.exit(2);
    }
  }
  process.exit(0);
});

// Collects recordings-src/live/*.json (made by the recorder from real live runs) into
// lib/liveRecordings.json and lib/exampleRequests.ts. Sorted by slug. Never edits recordings.
// Run: npm run recordings:live
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "recordings-src", "live");

const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json")) : [];
const recordings = files
  .map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")))
  .sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));

writeFileSync(join(root, "lib", "liveRecordings.json"), JSON.stringify({ recordings }, null, 2) + "\n");
writeFileSync(
  join(root, "lib", "exampleRequests.ts"),
  "// Generated by scripts/build-live-recordings.mjs. Do not edit by hand.\n" +
    `export const EXAMPLE_REQUESTS: string[] = ${JSON.stringify(recordings.map((r) => r.request), null, 2)};\n`,
);

for (const r of recordings) {
  console.log(r.request, "| approved", r.approved, "| rounds", r.rounds, "| cost $" + Number(r.costUsd).toFixed(3));
}
console.log(`${recordings.length} live recording(s) written.`);

// Collects recordings-src/live/*.json (made by the recorder from real live runs) into
// lib/liveRecordings.json (server), lib/liveRecordings/<slug>.json plus lib/liveRecordingChunks.ts (browser, one chunk
// per example), lib/liveRecordingsSummary.json and lib/exampleRequests.ts. Sorted by slug. Never edits recordings.
// Run: npm run recordings:live
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "recordings-src", "live");

const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json")) : [];
const recordings = files
  .map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")))
  .sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));

writeFileSync(join(root, "lib", "liveRecordings.json"), JSON.stringify({ recordings }, null, 2) + "\n");
writeFileSync(
  join(root, "lib", "exampleRequests.ts"),
  "// Generated by scripts/build-live-recordings.mjs. Do not edit by hand.\n" +
    `export const EXAMPLE_REQUESTS: string[] = ${JSON.stringify(recordings.map((r) => r.request), null, 2)};\n`,
);

// The browser loads only the example it plays, so each recording gets its own compact file and a lazy import.
const chunkDir = join(root, "lib", "liveRecordings");
rmSync(chunkDir, { recursive: true, force: true });
mkdirSync(chunkDir);
for (const r of recordings) writeFileSync(join(chunkDir, `${r.slug}.json`), JSON.stringify(r) + "\n");
writeFileSync(
  join(root, "lib", "liveRecordingChunks.ts"),
  "// Generated by scripts/build-live-recordings.mjs. Do not edit by hand.\n" +
    "export const RECORDING_CHUNKS: { request: string; load: () => Promise<{ default: unknown }> }[] = [\n" +
    recordings.map((r) => `  { request: ${JSON.stringify(r.request)}, load: () => import("./liveRecordings/${r.slug}.json") },\n`).join("") +
    "];\n",
);

// Small summary for the admin pages, so they never import the big recordings (screenshots).
const summary = recordings.map((r) => ({
  request: r.request,
  rounds: r.rounds,
  approved: r.approved,
  totalMs: r.totalMs,
  models: [...new Set(r.events.flatMap((e) => (e.event.type === "start" ? [e.event.model] : [])))],
  costUsd: r.events.reduce((sum, e) => sum + (e.event.type === "usage" ? e.event.costUsd : 0), 0),
}));
writeFileSync(join(root, "lib", "liveRecordingsSummary.json"), JSON.stringify(summary, null, 2) + "\n");

for (const r of recordings) {
  console.log(r.request, "| approved", r.approved, "| rounds", r.rounds, "| cost $" + Number(r.costUsd).toFixed(3));
}
console.log(`${recordings.length} live recording(s) written.`);
